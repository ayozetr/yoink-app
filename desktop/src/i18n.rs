//! Minimal i18n for the native UI. `tl(lang, key)` returns a UI string; the table
//! is a flat match so adding a language is just another arm (and more locales can
//! be slotted in the same way the web UI ships 14). The language is auto-detected
//! from the environment and overridable in Ajustes.

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Es,
    Fr,
    De,
    It,
    Pt,
    Ru,
    Pl,
    Uk,
    Id,
    Hi,
    Zh,
    Ja,
    Ko,
}

impl Lang {
    pub const ALL: [Lang; 14] = [
        Lang::En,
        Lang::Es,
        Lang::Fr,
        Lang::De,
        Lang::It,
        Lang::Pt,
        Lang::Ru,
        Lang::Pl,
        Lang::Uk,
        Lang::Id,
        Lang::Hi,
        Lang::Zh,
        Lang::Ja,
        Lang::Ko,
    ];

    /// Stable short code for persistence (ISO 639-1).
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Es => "es",
            Lang::Fr => "fr",
            Lang::De => "de",
            Lang::It => "it",
            Lang::Pt => "pt",
            Lang::Ru => "ru",
            Lang::Pl => "pl",
            Lang::Uk => "uk",
            Lang::Id => "id",
            Lang::Hi => "hi",
            Lang::Zh => "zh",
            Lang::Ja => "ja",
            Lang::Ko => "ko",
        }
    }

    /// Parse a code from [`Lang::code`].
    pub fn from_code(code: &str) -> Option<Lang> {
        Lang::ALL.into_iter().find(|l| l.code() == code)
    }

    pub fn label(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Es => "Español",
            Lang::Fr => "Français",
            Lang::De => "Deutsch",
            Lang::It => "Italiano",
            Lang::Pt => "Português (BR)",
            Lang::Ru => "Русский",
            Lang::Pl => "Polski",
            Lang::Uk => "Українська",
            Lang::Id => "Bahasa Indonesia",
            Lang::Hi => "हिन्दी",
            Lang::Zh => "简体中文",
            Lang::Ja => "日本語",
            Lang::Ko => "한국어",
        }
    }
}

/// Detect the language from `LANG`/`LC_ALL`/`LC_MESSAGES` (defaults to English).
pub fn detect() -> Lang {
    for var in ["LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(v) = std::env::var(var) {
            let v = v.to_lowercase();
            if v.starts_with("es") {
                return Lang::Es;
            }
            if v.starts_with("fr") {
                return Lang::Fr;
            }
            if v.starts_with("de") {
                return Lang::De;
            }
            if v.starts_with("it") {
                return Lang::It;
            }
            if v.starts_with("pt") {
                return Lang::Pt;
            }
            if v.starts_with("ru") {
                return Lang::Ru;
            }
            if v.starts_with("pl") {
                return Lang::Pl;
            }
            if v.starts_with("uk") {
                return Lang::Uk;
            }
            if v.starts_with("id") {
                return Lang::Id;
            }
            if v.starts_with("hi") {
                return Lang::Hi;
            }
            if v.starts_with("zh") {
                return Lang::Zh;
            }
            if v.starts_with("ja") {
                return Lang::Ja;
            }
            if v.starts_with("ko") {
                return Lang::Ko;
            }
            if !v.is_empty() {
                return Lang::En;
            }
        }
    }
    Lang::En
}

